# flood_tool/models/seven_class_tool.py
"""
Seven Class Flood Probability Model (KNN-enhanced for location prediction)
Based on postcode-level labelled samples
                                                                    – Kaiqing Deng

This model:
    - Trains a RandomForest classifier on postcode-level and district-level
      features generated by the preprocessing modules.
    - Is designed to work with the three high-level data functions in the tool.py:
          1. Function predict_flood_class_from_postcode
          2. Function predict_flood_class_from_OSGB36_location
          3. Function predict_flood_class_from_WGS84_locations

"""

import pandas as pd

from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler, OneHotEncoder, MinMaxScaler
from sklearn.ensemble import RandomForestClassifier
from sklearn.neighbors import NearestNeighbors


class SevenClassTool:
    """
    RandomForest-based flood-risk classifier.
    """
    # 1. Model Initialization
    def __init__(self, label_col: str = "riskLabel"):
        self.label_col = label_col

        # Model components
        self.pipeline_: Pipeline | None = None
        self.ref_df: pd.DataFrame | None = None
        self.nn: NearestNeighbors | None = None

        # Feature definitions
        self.num_std_cols = list(["easting", "northing", "elevation"])
        self.num_minmax_cols = list(["distanceToWatercourse"])
        self.cat_cols = list(["soilType", "nearestWatercourse", "localAuthority"])


    # 2. Fill Missing NearestWatercourse
    @staticmethod
    def _fill_watercourse(row: pd.Series) -> str:
        """
        FInd way to solve if 'nearestWatercourse' is missing.
        """
        wc = row.get("nearestWatercourse", None)
        dist = row.get("distanceToWatercourse", None)

        if pd.notna(wc):
            return wc

        if pd.notna(dist) and dist < 2000:
            return "UnknownNearbyWatercourse"

        return "NoWatercourse"

    # 3. Drop Features
    def _prepare_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Prepare raw feature DataFrame.
        """
        X = df.copy()

        # Ensure watercourse
        if "nearestWatercourse" not in X.columns:
            X["nearestWatercourse"] = None

        # Perform inference
        if "distanceToWatercourse" in X.columns:
            X["nearestWatercourse"] = X.apply(self._fill_watercourse, axis=1)

        # Drop non-feature columns
        drop_candidates = {"postcode", "medianPrice", self.label_col, "historicallyFlooded"}
        to_drop = list(drop_candidates.intersection(X.columns))
        X = X.drop(columns=to_drop)

        return X

    # 4. Prepare Pipeline
    def _prepare_pipeline(self) -> ColumnTransformer:
        """
        Construct preprocessing pipelines for different features.
        """
        numeric_tf_std = Pipeline([
                ("imputer", SimpleImputer(strategy="median")),
                ("scaler", StandardScaler()),
        ])

        numeric_tf_mm = Pipeline([
                ("imputer", SimpleImputer(strategy="median")),
                ("scaler", MinMaxScaler()),
        ])

        categorical_tf = Pipeline([
                ("imputer", SimpleImputer(strategy="most_frequent")),
                ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
        ])

        preprocessor = ColumnTransformer(
            transformers=[
                ("num_std", numeric_tf_std, self.num_std_cols),
                ("num_minmax", numeric_tf_mm, self.num_minmax_cols),
                ("cat", categorical_tf, self.cat_cols),
            ]
        )

        return preprocessor

    # Build Pipeline
    def _build_pipeline(self) -> Pipeline:
        """
        Build model pipeline
        """
        clf = RandomForestClassifier(
            n_estimators=400,
            min_samples_leaf=2,
            class_weight="balanced",
            random_state=42,
            n_jobs=-1,
        )

        return Pipeline([
                ("preprocessor", self._prepare_pipeline()),
                ("model", clf),
        ])

    # 6. Build KNN
    def set_reference_data(self, df_reference: pd.DataFrame):
        """
        Save feature data for KNN.
        """
        self.ref_df = df_reference.copy()

        # Build nearest neighbour model on easting/northing
        self.nn = NearestNeighbors(n_neighbors=1, algorithm="ball_tree")
        self.nn.fit(self.ref_df[["easting", "northing"]])

    # 7. Use KNN
    def lookup_features_from_location(self, df_locations: pd.DataFrame) -> pd.DataFrame:
        """
        Map raw location to the nearest postcode.
        """
        if self.nn is None or self.ref_df is None:
            raise RuntimeError(
                "Reference data missing. Call set_reference_data(...) after training."
            )

        distances, indices = self.nn.kneighbors(
            df_locations[["easting", "northing"]]
        )

        nearest_rows = self.ref_df.iloc[indices.flatten()].reset_index(drop=True)
        return nearest_rows


    # 8. Train Model
    def fit(self, unit_data: pd.DataFrame):
        """
        Train the model using postcode-level labelled samples.
        """
        if self.label_col not in unit_data.columns:
            raise KeyError(
                f"Can not find the '{self.label_col}' ."
            )

        df_train = unit_data.dropna(subset=[self.label_col]).copy()
        y = df_train[self.label_col]
        X_ = df_train.drop(columns=[self.label_col])

        X = self._prepare_features(X_)

        self.pipeline_ = self._build_pipeline()
        self.pipeline_.fit(X, y)

        return self

    # Analysis and Predict
    def predict_from_features(self, X_raw: pd.DataFrame, index=None) -> pd.Series:
        """
        Predict flood risk classification from raw feature rows.
        """
        if self.pipeline_ is None:
            raise RuntimeError("Model has not been fitted.")

        has_all_features = all(col in X_raw.columns for col in self.cat_cols)

        if has_all_features:
            X = self._prepare_features(X_raw)

        else:
            nearest = self.lookup_features_from_location(X_raw)
            X = self._prepare_features(nearest)

        preds = self.pipeline_.predict(X)

        if index is None:
            index = X_raw.index

        return pd.Series(preds, index=index, name=self.label_col)
